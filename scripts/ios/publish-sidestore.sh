#!/usr/bin/env bash
# Publishes a validated IPA and its SideStore/AltStore manifest on the public GitHub dist branch.
# Usage: scripts/ios/publish-sidestore.sh <ipa> [release notes] [screenshot]
# Run from the Vela checkout. The branch is force-pushed as one fresh commit so old IPAs do not
# accumulate in git history. Only the coordinator runs this after a green build. VELA_DIST_REMOTE and VELA_DIST_BRANCH can override the destination.
set -euo pipefail
ipa="$1"
notes="${2:-Latest Vela iOS development build.}"
screenshot="${3:-}"
[ -s "$ipa" ] || { echo "missing IPA: $ipa" >&2; exit 1; }
remote="${VELA_DIST_REMOTE:-git@github.com:gelinant/ios-builder.git}"
branch="${VELA_DIST_BRANCH:-dist}"
base="https://raw.githubusercontent.com/gelinant/ios-builder/$branch"
work="$(mktemp -d "${TMPDIR:-/tmp}/vela-sidestore.XXXXXX")"
trap 'rm -rf "$work"' EXIT
git clone -q --depth 1 --single-branch --branch "$branch" "$remote" "$work/dist" 2>/dev/null || {
  git init -q "$work/dist"
  git -C "$work/dist" checkout -q --orphan "$branch"
}
cp "$ipa" "$work/dist/Vela.ipa"
cp iosApp/Vela/Resources/Assets.xcassets/AppIcon.appiconset/AppIcon.png "$work/dist/icon.png"
[ -z "$screenshot" ] || cp "$screenshot" "$work/dist/screenshot.png"
[ -f "$work/dist/screenshot.png" ] || cp docs/logo.svg "$work/dist/screenshot.svg"
python3 scripts/ios/sidestore_source.py "$work/dist" "$base" "$notes"
cat > "$work/dist/README.md" <<EOF
# Vela iOS distribution

SideStore / AltStore source:
$base/apps.json

Add in SideStore:
sidestore://source?url=$(python3 -c 'import urllib.parse,sys; print(urllib.parse.quote(sys.argv[1], safe=""))' "$base/apps.json")

Only the latest validated development build is kept here. This branch is force-pushed as one
commit to avoid retaining old IPAs. Manifest generated by scripts/ios/sidestore_source.py.
EOF
git -C "$work/dist" add -A
git -C "$work/dist" -c user.name="Vela iOS CI" -c user.email="ios@localhost" commit -qm "iOS distribution: $notes"
git -C "$work/dist" push -q -f "$remote" HEAD:"$branch"
printf 'source: %s/apps.json\n' "$base"
printf 'add: sidestore://source?url=%s\n' "$(python3 -c 'import urllib.parse,sys; print(urllib.parse.quote(sys.argv[1], safe=""))' "$base/apps.json")"
