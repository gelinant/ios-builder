import Foundation
import SwiftUI
import VelaCore

/// The voice library: filesystem state, the selected id, downloads and the engine decision. The
/// installed set comes from `VoiceLayout`, never from a stored list, so a partial download cannot
/// claim to be usable.
final class VoiceLibrary: ObservableObject {
    static let shared = VoiceLibrary()

    @Published private(set) var installed: [String] = []
    @Published private(set) var selectedId: String?
    @Published private(set) var downloadingId: String?
    @Published private(set) var progress: Double = 0
    @Published private(set) var lastError: String?
    @Published private(set) var installing = false

    /// Debug launch switches from VoiceUITests. Never read in Release.
    private(set) var forceSystem = false
    /// Called before a voice directory is deleted, so the engine releases its model first.
    var beforeRemoving: ((String) -> Void)?

    let root: URL
    private let defaults: UserDefaults
    private let installer = VoiceModelInstaller()
    private var preparedFixture = false
    private static let selectedKey = "app.vela.ios.voice.model"

    init(root: URL = VoiceLayout.storeRoot(), defaults: UserDefaults = .standard) {
        self.root = root
        self.defaults = defaults
        refresh()
    }

    /// Applies the test launch arguments before the first engine decision. The fixture model is
    /// copied from the test bundle only in Debug builds; the release app has no bundled voice.
    func prepareForLaunch() {
        #if DEBUG
        if LaunchOptions.current.voiceDisableNeural { forceSystem = true }
        if LaunchOptions.current.voiceFixture { installFixtureFromBundle() }
        if ProcessInfo.processInfo.arguments.contains(Self.downloadFixtureArgument) {
            showDownloadFixture()
        }
        #endif
        installPlaceDictionaries()
    }

    #if DEBUG
    /// A static download row for the screenshot scenario: it starts no transfer and never touches
    /// the filesystem. The progress value is 42 percent, clearly mid-download. Test only.
    static let downloadFixtureArgument = "-VelaVoiceDownloadFixture"

    private func showDownloadFixture() {
        guard downloadingId == nil else { return }
        guard let entry = VoiceCatalog.all.first(where: { !isInstalled($0.id) }) else { return }
        downloadingId = entry.id
        installing = false
        progress = 0.42
    }
    #endif

    /// Reinstalls the bundled place-name dictionary into every English voice whose recorded
    /// version is stale. Idempotent: a marker file makes this a stat per voice after the first run.
    func installPlaceDictionaries() {
        for id in installed {
            PlaceDictionary.install(voiceID: id, dataDir: VoiceLayout.dataPath(id: id, root: root))
        }
    }

    /// Guidance language, as generated by the shared NavStrings tables.
    var guidanceLanguage: String {
        let language = NavStringsRegistry.shared.current().language
        return language.isEmpty ? "en" : language
    }

    /// The Piper language prefix for the guidance language (`pt-br` and `zh-tw` still need `pt`
    /// and `zh` models).
    var voiceLanguage: String {
        IosVoiceSelection.shared.languageOf(tagOrId: guidanceLanguage)
    }

    /// The precise table tag, for labels: Brazilian Portuguese and Traditional Chinese share a
    /// language code with their European and Simplified counterparts.
    var guidanceLanguageTag: String {
        let nav = NavStringsRegistry.shared.current()
        if nav.language == "zh" && nav.region == "TW" { return "zh-tw" }
        if nav.language == "pt" && nav.region == "BR" { return "pt-br" }
        return guidanceLanguage
    }

    var effectiveId: String? {
        IosVoiceSelection.shared.effectiveVoiceId(
            installed: installed, selected: selectedId, language: guidanceLanguage)
    }

    /// The catalog voice actually speaking, or nil when the iPhone voice is used.
    var effectiveEntry: VoiceEntry? {
        effectiveId.flatMap { VoiceCatalog.entry($0) }
    }

    /// A downloadable Vela voice exists for this guidance language. Japanese and Hebrew have none.
    var hasCatalogVoice: Bool {
        DirectionsLanguage.shared.hasNeuralVoice(tag: guidanceLanguage)
    }

    /// Voices of the guidance language that are installed, for the section's status lines.
    var installedForGuidance: [VoiceEntry] {
        installedEntries.filter { $0.language == voiceLanguage }
    }

    /// Voices installed for other languages. They cannot speak the current directions.
    var installedForOtherLanguages: [VoiceEntry] {
        installedEntries.filter { $0.language != voiceLanguage }
    }

    var engine: String {
        if forceSystem { return "system" }
        return IosVoiceSelection.shared.engine(
            installed: installed, selected: selectedId, language: guidanceLanguage)
    }

    var fallbackReason: String? {
        if forceSystem { return "disabled-for-test" }
        return IosVoiceSelection.shared.fallbackReason(
            installed: installed, selected: selectedId, language: guidanceLanguage)
    }

    var engineDebug: String {
        if let id = effectiveId, engine == "neural" {
            return "engine=neural voice=\(id)"
        }
        return "engine=system reason=\(fallbackReason ?? "unknown")"
    }

    var recommended: VoiceEntry? {
        guard let entry = VoiceCatalog.recommended(language: guidanceLanguage),
              entry.language == IosVoiceSelection.shared.languageOf(tagOrId: guidanceLanguage) else {
            return nil
        }
        return entry
    }

    var installedEntries: [VoiceEntry] {
        installed.map { VoiceEntry(id: $0) }
    }

    func entry(_ id: String) -> VoiceEntry? { VoiceCatalog.entry(id) }

    func isInstalled(_ id: String) -> Bool { installed.contains(id) }

    func isInUse(_ id: String) -> Bool { effectiveId == id && !forceSystem }

    func currentVoiceFiles() -> SherpaTts.VoiceFiles? {
        guard !forceSystem, let id = effectiveId, VoiceLayout.isComplete(id: id, root: root) else {
            return nil
        }
        return SherpaTts.VoiceFiles(
            id: id,
            model: VoiceLayout.modelPath(id: id, root: root),
            tokens: VoiceLayout.tokensPath(id: id, root: root),
            dataDir: VoiceLayout.dataPath(id: id, root: root))
    }

    func select(_ id: String) {
        guard isInstalled(id) else { return }
        defaults.set(id, forKey: Self.selectedKey)
        selectedId = id
        objectWillChange.send()
    }

    func refresh() {
        let update = { [weak self] in
            guard let self else { return }
            self.selectedId = self.defaults.string(forKey: Self.selectedKey)
            self.installed = VoiceLayout.installed(root: self.root)
            self.objectWillChange.send()
        }
        if Thread.isMainThread { update() } else { DispatchQueue.main.async(execute: update) }
    }

    /// Download and install a catalog voice, then select it. One download at a time.
    func install(_ id: String) {
        guard VoiceInstallRules.shared.canStartDownload(
            installed: isInstalled(id), downloadingId: downloadingId),
              let entry = VoiceCatalog.entry(id) else { return }
        guard let url = URL(string: entry.downloadUrl) else { return }
        downloadingId = id
        installing = false
        progress = 0
        lastError = nil
        Task { [weak self] in
            guard let self else { return }
            do {
                try await self.installer.install(
                    id: id, url: url,
                    progress: { value in DispatchQueue.main.async { self.progress = value } },
                    installing: { DispatchQueue.main.async {
                        self.installing = true
                        self.progress = 0.9
                    } })
                await MainActor.run {
                    self.downloadingId = nil
                    self.installing = false
                    self.progress = 1
                    self.refresh()
                    self.installPlaceDictionaries()
                    self.select(id)
                }
            } catch {
                await MainActor.run {
                    self.downloadingId = nil
                    self.installing = false
                    self.lastError = error.localizedDescription
                }
            }
        }
    }

    func remove(_ id: String) {
        beforeRemoving?(id)
        try? FileManager.default.removeItem(at: VoiceLayout.directory(id: id, root: root))
        if VoiceInstallRules.shared.selectionAfterRemove(removedId: id, selectedId: selectedId) == nil {
            defaults.removeObject(forKey: Self.selectedKey)
        }
        refresh()
    }

    /// Row controls from the shared rules, so the section and the library agree.
    func rowStatus(_ id: String) -> VoiceRowStatus {
        VoiceInstallRules.shared.row(
            installed: isInstalled(id),
            inUse: isInUse(id),
            downloadingId: downloadingId,
            id: id,
            installing: installing,
            progress: progress)
    }

    func clearError() { lastError = nil }

    /// Copies the fixture directory from the test bundle once. CI puts an expanded
    /// `vits-piper-<id>` folder under `Vela.app/VoiceFixture/`; a release build has none.
    func installFixtureFromBundle() {
        guard !preparedFixture else { return }
        preparedFixture = true
        guard let source = Bundle.main.url(forResource: "VoiceFixture", withExtension: nil) else { return }
        let fm = FileManager.default
        let ids = (try? fm.contentsOfDirectory(at: source, includingPropertiesForKeys: nil)) ?? []
        for id in ids.map(\.lastPathComponent) where VoiceLayout.isComplete(id: id, root: source) {
            guard !VoiceLayout.isComplete(id: id, root: root) else { continue }
            let destination = VoiceLayout.directory(id: id, root: root)
            try? fm.createDirectory(at: root, withIntermediateDirectories: true)
            try? fm.removeItem(at: destination)
            try? fm.copyItem(at: source.appendingPathComponent(id), to: destination)
        }
        refresh()
    }
}
